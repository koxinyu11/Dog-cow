/** A dish listed under two categories keeps its first listing. */
export const MEAL_CATALOG: CatalogMeal[] = RAW_CATALOG.filter((meal, i) => RAW_CATALOG.findIndex(m => m.name === meal.name) === i);
const byName = new Map(MEAL_CATALOG.map(meal => [meal.name, meal]));
export const findMeal = (name: string) => byName.get(name.trim());

/** Catalog category, or a keyword guess for custom dishes. Null when nothing fits. */
export function mealCategory(name: string): MealCategoryId | null {
  const known = findMeal(name);
  if (known) return known.category;
  if (/奶茶|咖啡|拿铁|果茶|柠檬茶|汁|饮|水$|茶$/.test(name)) return 'drink';
  if (/蛋糕|冰淇淋|布丁|甜|糕|冰$/.test(name)) return 'dessert';
  if (/汉堡|薯条|鸡块/.test(name)) return 'fastfood';
  if (/牛排|披萨|意面|意大利/.test(name)) return 'western';
  if (/火锅|烧烤|烤|串|锅|冒菜|麻辣烫/.test(name)) return 'hotpot';
  if (/粥|汤|羹/.test(name)) return 'soup';
  if (/沙拉|轻食|蔬菜|低脂/.test(name)) return 'light';
  if (/面|粉|线|饺|馄饨/.test(name)) return 'noodle';
  if (/饭|煲仔|盖浇/.test(name)) return 'rice';
  if (/炸|饼|包子|三明治/.test(name)) return 'snack';
  if (/寿司|日式|韩式|泰式|咖喱/.test(name)) return 'world';
  if (/炒|烧|焖|蒸|煎|红烧/.test(name)) return 'home';
  return null;
}
export const mealEmoji = (name: string) => findMeal(name)?.emoji ?? MEAL_CATEGORIES.find(c => c.id === mealCategory(name))?.emoji ?? '🍽️';
export function mealQuip(name: string, random = Math.random) {
  const quips = MEAL_CATEGORIES.find(c => c.id === mealCategory(name))?.quips ?? GENERIC_QUIPS;
  return quips[Math.floor(random() * quips.length)];
}
