// Full application acceptance with a temporary profile. Never targets the installed app.
const { app, BrowserWindow } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const root = process.env.DOGCOW_REPO;
const profile = process.env.DOGCOW_TEST_PROFILE;
assert.equal(process.env.NODE_ENV, 'test');
assert.ok(profile && path.basename(profile) === 'profile' && path.basename(path.dirname(profile)).startsWith('dogcow-fishing-test-'));
app.setAppPath(root);
const load = file => import(pathToFileURL(path.join(root, 'dist-electron', file)).href);
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
async function until(read, label) {
  for (let i = 0; i < 150; i++) { const value = await read(); if (value) return value; await sleep(50); }
  throw Error(`timeout: ${label}`);
}
const js = (win, source) => win.webContents.executeJavaScript(source);
const count = win => js(win, "document.querySelectorAll('.df-species').length");
const rarity = (win, value) => js(win, `(() => { const select = document.querySelector('.df-book-filter select'); select.value = ${JSON.stringify(value)}; select.dispatchEvent(new Event('change', { bubbles:true })); })()`);
const shelf = (win, text) => js(win, `(() => { const button = [...document.querySelectorAll('.df-shelves button')].find(b => b.textContent.includes(${JSON.stringify(text)})); button.click(); })()`);
const shot = async (win, name) => fs.writeFile(path.join(process.env.DOGCOW_FISHING_ARTIFACTS, name), (await win.webContents.capturePage()).toPNG());

(async () => {
  await load('src/main/main.js');
  const main = await until(() => BrowserWindow.getAllWindows().find(w => w.webContents.getURL() === 'dogcow://app/index.html'), 'main window');
  await until(() => js(main, "!!window.dogcow && !!document.querySelector('button[aria-label=\"狗牛游乐场\"]')"), 'main launcher');
  assert.equal(app.getPath('userData'), profile);
  assert.equal(await js(main, "window.dogcow.invoke('openPlayground').then(r => r.applied)"), true);
  let park = await until(() => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().endsWith('/playground.html')), 'playground');
  await until(() => js(park, "!![...document.querySelectorAll('button')].find(b => b.textContent.includes('工位钓鱼'))"), 'fishing card');
  await js(park, "[...document.querySelectorAll('button')].find(b => b.textContent.includes('工位钓鱼')).click()");
  await until(() => js(park, "(() => { document.querySelector('.pg-pause button')?.click(); return !!document.querySelector('.df-game button[aria-label=\"图鉴\"]:not(:disabled)'); })()"), 'fishing game');
  assert.ok((await js(park, "document.querySelector('.df-chip-link').textContent")).includes('100/100'));
  await js(park, "document.querySelector('.df-game button[aria-label=\"图鉴\"]').click()");
  await until(async () => await count(park) === 72, '72 fish');
  await rarity(park, '5'); await until(async () => await count(park) === 8, '8 mythic fish');
  assert.ok((await js(park, "document.querySelector('.df-detail').textContent")).includes('星砂锦鲤'));
  park.setContentSize(1280, 900); await sleep(150); await shot(park, 'mythic-fish.png');
  await shelf(park, '稀有宝物'); await until(async () => await count(park) === 2, '2 mythic treasures');
  await js(park, "[...document.querySelectorAll('.df-species')].find(b => b.textContent.includes('失落王冠')).click()");
  assert.ok((await js(park, "document.querySelector('.df-detail').textContent")).includes('失落王冠'));
  await shot(park, 'mythic-treasures.png');
  await shelf(park, '水边生物'); await until(() => js(park, "!!document.querySelector('.df-book-empty')"), 'empty rarity filter');
  assert.equal(await count(park), 0);
  await rarity(park, 'all'); await until(async () => await count(park) === 10, '10 creatures');
  await shelf(park, '工位旧物'); await until(async () => await count(park) === 8, '8 old objects');
  await shelf(park, '稀有宝物'); await until(async () => await count(park) === 10, '10 treasures');
  park.setContentSize(800, 600); await sleep(150);
  assert.equal(await js(park, "(() => { const r = document.querySelector('.df-modal').getBoundingClientRect(); return r.left >= 0 && r.right <= innerWidth + 1 && r.top >= 0 && r.bottom <= innerHeight + 1; })()"), true);
  await shot(park, 'treasures-800x600.png');
  await js(main, "localStorage.setItem('dogcow.ui.theme', 'dark'); true");
  await new Promise(resolve => { main.webContents.once('did-finish-load', resolve); main.webContents.reload(); });
  await until(() => js(park, "document.documentElement.dataset.theme === 'dark'"), 'dark theme');
  await js(park, "document.querySelector('.pg-pause button')?.click()");
  await rarity(park, '5'); await until(async () => await count(park) === 2, 'dark mythic treasures');
  await sleep(150); await shot(park, 'treasures-dark.png');
  await js(park, "document.querySelector('.df-modal-close').click()");
  await until(() => js(park, "!document.querySelector('.df-modal')"), 'close book');
  await js(park, "document.querySelector('.pg-pause button')?.click()");
  await js(park, "document.querySelector('.df-game button[aria-label^=\"鱼篓\"]').click()");
  await until(() => js(park, "document.querySelectorAll('.df-bag-item').length === 97"), 'bag with visitors excluded');
  assert.equal(await js(park, "document.querySelectorAll('.df-bag-item.rarity-5.is-locked').length"), 10);
  console.log('PASS: actual application launcher → fishing → 100-entry book; rarity/category/empty states, small window, theme and locked mythic bag');

  // Exercise the real renderer, IPC, wallet and persistent equipment together.
  await js(park, "document.querySelector('.df-modal-close').click(); document.querySelector('.pg-pause button')?.click()");
  await until(() => js(park, "!!document.querySelector('.df-game button[aria-label=\"商店\"]:not(:disabled)')"), 'shop entry');
  await js(park, "document.querySelector('.df-game button[aria-label=\"商店\"]').click()");
  const shopTab = name => js(park, `(() => { [...document.querySelectorAll('.df-seg button')].find(b => b.textContent === ${JSON.stringify(name)}).click(); })()`);
  const clickReady = async (selector, label) => {
    await until(() => js(park, `(() => { document.querySelector('.pg-pause button')?.click(); return !!document.querySelector(${JSON.stringify(selector + ':not(:disabled)')}); })()`), label);
    await js(park, `document.querySelector(${JSON.stringify(selector)}).click()`);
  };
  const gameState = () => js(park, "window.playground.fishing({action:'view'}).then(r => r.view.state)");
  await until(() => js(park, "!!document.querySelector('.df-seg')"), 'shop tabs');
  await shopTab('皮肤'); await until(() => js(park, "document.querySelectorAll('[data-skin-card]').length === 7"), 'skin cards');
  await clickReady('[data-skin-card="starlight"] .df-skin-preview', 'skin preview');
  await until(() => js(park, "!!document.querySelector('[data-skin-preview=\"starlight\"]')"), 'preview changes');
  assert.equal((await gameState()).gear.skin, 'default', 'preview must not equip or spend');
  await clickReady('[data-skin-card="mint"] .df-price', 'buy mint');
  await until(async () => (await gameState()).gear.skin === 'mint', 'mint persisted');
  await until(() => js(park, "!!document.querySelector('.df-landscape g[data-rod-skin=\"mint\"]')"), 'mint in actual scene');
  assert.equal(await js(park, "window.playground.fishing({action:'view'}).then(r => r.view.balance)"), 982);
  await clickReady('[data-skin-card="galaxy"] .df-ghost', 'earned skin');
  await until(async () => (await gameState()).gear.skin === 'galaxy', 'reward equipped');
  await clickReady('[data-skin-card="galaxy"] .df-skin-preview', 'reward preview');
  park.setContentSize(1280, 900); await sleep(150); await shot(park, 'gear-skins.png');
  await shopTab('补给'); await until(() => js(park, "document.querySelectorAll('[data-supply-card]').length === 4"), 'supplies and repair');
  for (const id of ['scout', 'magnet', 'guard']) {
    await clickReady(`[data-supply-card="${id}"] .df-price`, `buy ${id}`);
    await until(async () => (await gameState()).gear.stock[id] > 0, `${id} persisted`);
  }
  await clickReady('[data-supply-card="repair"] .df-price', 'repair rod');
  await until(async () => (await gameState()).wear.collector === 100, 'repair persisted');
  assert.equal(await js(park, "window.playground.fishing({action:'view'}).then(r => r.view.balance)"), 759);
  await shot(park, 'gear-supplies.png');
  park.setContentSize(800, 600); await sleep(150); await shot(park, 'gear-supplies-800x600.png');
  assert.equal(await js(park, "(() => { const e = document.querySelector('.df-modal-body'); return e.scrollWidth <= e.clientWidth + 1; })()"), true);
  await js(park, "document.querySelector('.df-modal-close').click(); document.querySelector('.pg-pause button')?.click()");
  await until(() => js(park, "!document.querySelector('.df-modal')"), 'supplies dialog closed');
  await until(() => js(park, "!!document.querySelector('.df-loadout select:not(:disabled)')"), 'loadout ready');
  await js(park, "(() => { const e = document.querySelector('.df-loadout select'); e.value='scout'; e.dispatchEvent(new Event('change',{bubbles:true})); })()");
  await until(async () => (await gameState()).bait === 'scout', 'scout equipped');
  await clickReady('.df-guard', 'guard enabled');
  await until(async () => (await gameState()).gear.guard, 'guard persisted');
  await shot(park, 'gear-equipped.png');
  console.log('Equipment cast readiness:', await js(park, "({ paused:!!document.querySelector('.pg-pause'), modal:!!document.querySelector('.df-modal'), phase:document.querySelector('.df-main-action')?.dataset.phase, disabled:document.querySelector('.df-main-action button')?.disabled })"));
  await clickReady('.df-main-action button', 'cast with supplies');
  const pending = await until(async () => (await gameState()).round, 'stored round');
  assert.equal((await gameState()).gear.stock.scout, 10);
  assert.equal(await js(park, "document.querySelector('.df-loadout select').disabled"), true);
  park.close(); await until(() => park.isDestroyed(), 'close game while fishing');
  assert.equal(await js(main, "window.dogcow.invoke('openPlayground').then(r => r.applied)"), true);
  park = await until(() => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().endsWith('/playground.html')), 'reopen playground');
  park.focus();
  await until(() => js(park, "!![...document.querySelectorAll('button')].find(b => b.textContent.includes('工位钓鱼'))"), 'reopened fishing card');
  await js(park, "[...document.querySelectorAll('button')].find(b => b.textContent.includes('工位钓鱼')).click()");
  await until(() => js(park, "(() => { document.querySelector('.pg-pause button')?.click(); return !!document.querySelector('.df-game'); })()"), 'resumed fishing');
  assert.equal((await gameState()).round.id, pending.id);
  assert.equal((await gameState()).gear.skin, 'galaxy');
  await until(() => js(park, "(() => { document.querySelector('.pg-pause button')?.click(); return document.querySelector('.df-main-action')?.dataset.phase === 'signal'; })()"), 'bite after reopening');
  await clickReady('.df-main-action button', 'reel after reopening');
  await until(async () => !(await gameState()).round, 'settled reel');
  assert.equal((await gameState()).gear.stock.scout, 9);
  assert.equal((await gameState()).gear.stock.guard, 1);
  console.log('PASS: real preview/purchase/reward equip, exact wallet prices, supplies, repair, scene skin, small layout and one consumption after close/reopen');

  const gallery = new BrowserWindow({ width: 1400, height: 1560, show: false, webPreferences: { sandbox: true, backgroundThrottling: false } });
  await gallery.loadFile(process.env.DOGCOW_FISHING_FIXTURE);
  await until(() => js(gallery, "document.querySelectorAll('article[data-species] svg.df-art').length === 100"), '100 rendered illustrations');
  assert.equal(await js(gallery, "[...document.querySelectorAll('svg.df-art')].every(svg => svg.querySelectorAll('path,circle,ellipse,rect').length > 1 && !svg.innerHTML.includes('NaN'))"), true);
  assert.equal(await js(gallery, "document.querySelectorAll('[data-skin-variant] svg.df-rod-art').length"), 28);
  assert.equal(await js(gallery, "[...document.querySelectorAll('[data-skin-variant] svg')].every(svg => !svg.innerHTML.includes('NaN'))"), true);
  gallery.webContents.debugger.attach('1.3');
  await gallery.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] });
  assert.equal(await js(gallery, "getComputedStyle(document.querySelector('.df-art.rarity-4')).animationName"), 'none');
  await js(gallery, 'document.fonts.ready.then(() => true)');
  gallery.setContentSize(1400, await js(gallery, 'document.documentElement.scrollHeight'));
  await sleep(150);
  assert.equal(await js(gallery, "document.querySelector('article:last-child[data-species=\"year-end-envelope\"]').getBoundingClientRect().bottom <= innerHeight"), true);
  await shot(gallery, 'all-100.png');
  console.log('PASS: 100 SVG illustrations and all 28 rod/skin combinations rendered, no invalid geometry, reduced motion supported');
  gallery.destroy();
  app.exit(0);
})().catch(error => { console.error(error); app.exit(1); });
