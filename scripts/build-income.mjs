import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';

const project = fileURLToPath(new URL('../', import.meta.url));
await build({
  absWorkingDir: project,
  entryPoints: ['app/income/src/entry.js'],
  outfile: 'app/income/income.bundle.js',
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['safari15.4'],
  loader: { '.html': 'text', '.css': 'text' },
  charset: 'utf8',
  legalComments: 'inline',
  banner: { js: '// Generated by npm run build:income. Edit app/income/src instead.\n// Holiday data: Copyright (c) 2019 NateScarlet, MIT; see income/data/holidays/LICENSE.holiday-cn.txt.' },
  logLevel: 'info',
});
